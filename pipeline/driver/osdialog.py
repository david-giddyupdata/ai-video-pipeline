"""A Windows dialog the page opened (R112: the upload's Open dialog, shown whole), driven through UI Automation.

The runner draws the cursor in the edit (R17) and the real pointer stays off the capture monitor (R15), so nothing here
moves or clicks the mouse: an item is selected with its SelectionItem pattern and a button pressed with its Invoke
pattern, which is what a click does. Boxes are screen pixels (every monitor is at 100% scaling, SPEC §9).

    python -m pipeline.driver.osdialog [title]    # list what an open dialog shows: its folder, items and buttons
"""
import sys
import time

import comtypes
import comtypes.client
import win32api
import win32gui
import win32process

comtypes.client.GetModule("UIAutomationCore.dll")
from comtypes.gen import UIAutomationClient as U   # noqa: E402  (generated by GetModule above)

_uia = None


def uia():
    global _uia
    if _uia is None:
        comtypes.CoInitialize()
        _uia = comtypes.CoCreateInstance(U.CUIAutomation._reg_clsid_, interface=U.IUIAutomation,
                                         clsctx=comtypes.CLSCTX_INPROC_SERVER)
    return _uia


def _and(**props):
    ids = {"name": U.UIA_NamePropertyId, "cls": U.UIA_ClassNamePropertyId, "type": U.UIA_ControlTypePropertyId}
    conds = [uia().CreatePropertyCondition(ids[k], v) for k, v in props.items()]
    return conds[0] if len(conds) == 1 else uia().CreateAndCondition(*conds[:2])


def _exe(hwnd):
    try:
        _, pid = win32process.GetWindowThreadProcessId(hwnd)
        h = win32api.OpenProcess(0x1000, False, pid)                  # PROCESS_QUERY_LIMITED_INFORMATION
        return win32process.GetModuleFileNameEx(h, 0).rsplit("\\", 1)[-1].lower()
    except Exception:
        return "?"


def _hwnd(title, exe="msedge.exe"):
    """The visible top-level dialog window (#32770) with this title that Edge opened (another program's Open dialog
    doesn't count). UI Automation lists a dialog under the window that owns it, not under the desktop, so it is found
    as a window first."""
    found = []

    def cb(h, _):
        if not found and win32gui.IsWindowVisible(h) and win32gui.GetClassName(h) == "#32770" \
                and win32gui.GetWindowText(h) == title and _exe(h) == exe:
            found.append(h)
        return True

    win32gui.EnumWindows(cb, None)
    return found[0] if found else None


def find_dialog(title="Open", timeout_s=10.0):
    """The dialog with this title, as soon as it appears."""
    end = time.time() + timeout_s
    while True:
        h = _hwnd(title)
        if h:
            return uia().ElementFromHandle(h)
        if time.time() >= end:
            raise TimeoutError(f"no '{title}' dialog after {timeout_s:.0f} s")
        time.sleep(0.1)


def _pattern(el, pid, iface):
    """A control pattern, or None: an element without it gives a NULL pointer, not a COMError."""
    pat = el.GetCurrentPattern(pid)
    return pat.QueryInterface(iface) if pat else None


def item(dlg, name):
    """A list item (a file in the Open dialog's view), scrolled into view."""
    el = dlg.FindFirst(U.TreeScope_Descendants, _and(type=U.UIA_ListItemControlTypeId, name=name))
    if not el:
        raise RuntimeError(f"no item '{name}' in the dialog")
    scroll = _pattern(el, U.UIA_ScrollItemPatternId, U.IUIAutomationScrollItemPattern)
    if scroll:
        scroll.ScrollIntoView()
    return el


def button(dlg, name):
    """The widest button with this name: the Open dialog has three named Open (the file-type and split-button arrows
    are narrow)."""
    els = [e for t in (U.UIA_ButtonControlTypeId, U.UIA_SplitButtonControlTypeId) for e in _all(dlg, t)
           if e.CurrentName == name]
    if not els:
        raise RuntimeError(f"no button '{name}' in the dialog")
    return max(els, key=lambda e: box(e)[2] - box(e)[0])


def box(el):
    """(left, top, right, bottom) in screen px."""
    r = el.CurrentBoundingRectangle
    return r.left, r.top, r.right, r.bottom


def name_box(dlg, el):
    """An item's name cell, if the view has one (Details view: the row spans every column); else the item itself."""
    cell = el.FindFirst(U.TreeScope_Children, _and(type=U.UIA_EditControlTypeId))
    if not cell:
        cell = el.FindFirst(U.TreeScope_Children, _and(type=U.UIA_TextControlTypeId))
    return box(cell) if cell else box(el)


def folder(dlg):
    """The folder the dialog shows: its address bar reads "Address: <path>"."""
    for tb in _all(dlg, U.UIA_ToolBarControlTypeId):
        if (tb.CurrentName or "").startswith("Address: "):
            return tb.CurrentName[len("Address: "):]
    return None


def _all(el, control_type):
    arr = el.FindAll(U.TreeScope_Descendants, _and(type=control_type))
    return [arr.GetElement(i) for i in range(arr.Length)]


def select(el):
    pat = _pattern(el, U.UIA_SelectionItemPatternId, U.IUIAutomationSelectionItemPattern)
    if not pat:
        raise RuntimeError(f"{el.CurrentName!r} can't be selected (no SelectionItem pattern)")
    pat.Select()


def invoke(el):
    pat = _pattern(el, U.UIA_InvokePatternId, U.IUIAutomationInvokePattern)
    if not pat:
        raise RuntimeError(f"{el.CurrentName!r} can't be pressed (no Invoke pattern)")
    pat.Invoke()


def file_name(dlg):
    """What the File name box holds (it follows the selection)."""
    for e in _all(dlg, U.UIA_EditControlTypeId):
        if (e.CurrentName or "").startswith("File name"):
            val = _pattern(e, U.UIA_ValuePatternId, U.IUIAutomationValuePattern)
            return val.CurrentValue if val else None
    return None


def is_open(title="Open"):
    return _hwnd(title) is not None


if __name__ == "__main__":
    dlg = find_dialog(sys.argv[1] if len(sys.argv) > 1 else "Open", 2)
    print("dialog", box(dlg), "folder:", folder(dlg), "file name:", file_name(dlg))
    for e in _all(dlg, U.UIA_ListItemControlTypeId):
        print("  item", repr(e.CurrentName), box(e), "name cell", name_box(dlg, e))
    for e in _all(dlg, U.UIA_ButtonControlTypeId) + _all(dlg, U.UIA_SplitButtonControlTypeId):
        if e.CurrentName:
            print("  button", repr(e.CurrentName), box(e))
